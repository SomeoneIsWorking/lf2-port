#!/usr/bin/env python3
"""Compile authoritative GLSL shaders to committed SPIR-V and Metal headers.

The runtime consumes the committed headers, so neither compiler is a build-time
dependency.  This tool is the one owner of both payload formats: glslc compiles
GLSL to SPIR-V, then the official SDL_shadercross CLI translates that exact
SPIR-V to Metal Shading Language.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADER_SUFFIXES = {".frag": "fragment", ".vert": "vertex"}


def shader_name(source: Path) -> str:
    """Return the collision-free generated name used by the runtime."""
    return source.stem + ("_vert" if source.suffix == ".vert" else "")


def shader_sources(root: Path) -> list[tuple[Path, str, str]]:
    source_dir = root / "runtime" / "shaders"
    sources: list[tuple[Path, str, str]] = []
    for suffix, stage in SHADER_SUFFIXES.items():
        for source in source_dir.glob(f"*{suffix}"):
            sources.append((source, stage, shader_name(source)))
    return sorted(sources)


def c_header(
    source: Path, root: Path, symbol: str, format_name: str, payload: bytes
) -> bytes:
    relative_source = source.relative_to(root).as_posix()
    rows = []
    for offset in range(0, len(payload), 16):
        values = ",".join(str(value) for value in payload[offset : offset + 16])
        rows.append(f"    {values},")
    body = "\n".join(rows)
    return (
        f"/* GENERATED by tools/build/build_shaders.py from {relative_source} -- do not edit.\n"
        " * Regenerate and commit after changing GLSL; ctest shaders checks both formats. */\n"
        f"static const unsigned char {symbol}_{format_name}[] = {{\n"
        f"{body}\n"
        "};\n"
    ).encode("ascii")


def configured_tool(
    variable: str, fallback: str, environment: Mapping[str, str]
) -> tuple[str, str | None]:
    requested = environment.get(variable) or fallback
    return requested, shutil.which(requested, path=environment.get("PATH"))


def report_missing(missing: Sequence[tuple[str, str]], check: bool) -> int:
    prefix = "SKIP" if check else "FAIL"
    names = ", ".join(f"{variable}={requested}" for variable, requested in missing)
    print(f"{prefix}: shader generation requires executable tool(s): {names}")
    print("      glslc compiles authoritative GLSL to SPIR-V; the official")
    print("      libsdl-org/SDL_shadercross artifact translates that SPIR-V to MSL.")
    print("      Set GLSLC and SHADERCROSS to their executable paths when not on PATH.")
    return 77 if check else 1


def run_command(command: Sequence[str], environment: Mapping[str, str]) -> None:
    result = subprocess.run(command, env=dict(environment), check=False)
    if result.returncode:
        raise RuntimeError(f"command exited {result.returncode}: {' '.join(command)}")


def compile_spirv(
    source: Path,
    stage: str,
    name: str,
    temp_dir: Path,
    glslc: str,
    environment: Mapping[str, str],
) -> tuple[Path, bytes]:
    spirv_path = temp_dir / f"{name}.spv"
    run_command(
        [glslc, "-O", f"-fshader-stage={stage}", str(source), "-o", str(spirv_path)],
        environment,
    )
    if not spirv_path.is_file():
        raise RuntimeError(f"glslc did not produce SPIR-V for {source}")
    return spirv_path, spirv_path.read_bytes()


def compile_msl(
    source: Path,
    stage: str,
    name: str,
    temp_dir: Path,
    spirv_path: Path,
    shadercross: str,
    environment: Mapping[str, str],
) -> bytes:
    msl_path = temp_dir / f"{name}.msl"
    run_command(
        [
            shadercross,
            str(spirv_path),
            "--source",
            "SPIRV",
            "--dest",
            "MSL",
            "--stage",
            stage,
            "--entrypoint",
            "main",
            "--output",
            str(msl_path),
        ],
        environment,
    )
    if not msl_path.is_file():
        raise RuntimeError(f"SDL_shadercross did not produce MSL for {source}")
    return msl_path.read_bytes()


def process_shaders(root: Path, environment: Mapping[str, str], check: bool) -> int:
    sources = shader_sources(root)
    if not sources:
        print(
            "FAIL: runtime/shaders held no .frag or .vert files, so NOTHING was compiled or checked"
        )
        return 1

    _, glslc = configured_tool("GLSLC", "glslc", environment)
    _, shadercross = configured_tool("SHADERCROSS", "shadercross", environment)
    if glslc is None:
        requested, _ = configured_tool("GLSLC", "glslc", environment)
        return report_missing([("GLSLC", requested)], check)
    if shadercross is None and not check:
        requested, _ = configured_tool("SHADERCROSS", "shadercross", environment)
        return report_missing([("SHADERCROSS", requested)], check)

    generated_dir = root / "runtime" / "shaders" / "gen"
    generated_dir.mkdir(parents=True, exist_ok=True)
    scratch_dir = root / "scratch"
    scratch_dir.mkdir(parents=True, exist_ok=True)
    status = 0

    try:
        with tempfile.TemporaryDirectory(
            prefix="shader-build-", dir=scratch_dir
        ) as temporary:
            temp_dir = Path(temporary)
            for source, stage, name in sources:
                spirv_path, spirv = compile_spirv(
                    source, stage, name, temp_dir, glslc, environment
                )
                outputs = [("spv", spirv, generated_dir / f"{name}_spv.h")]
                if shadercross is not None:
                    msl = compile_msl(
                        source,
                        stage,
                        name,
                        temp_dir,
                        spirv_path,
                        shadercross,
                        environment,
                    )
                    outputs.append(("msl", msl, generated_dir / f"{name}_msl.h"))
                for format_name, payload, output in outputs:
                    expected = c_header(source, root, name, format_name, payload)
                    if check:
                        if not output.is_file():
                            print(
                                f"FAIL: {output.relative_to(root)} is missing -- run tools/build/build_shaders.py"
                            )
                            status = 1
                        elif output.read_bytes() != expected:
                            print(
                                f"FAIL: {output.relative_to(root)} is stale -- "
                                f"{source.relative_to(root)} or its compiler output has changed"
                            )
                            status = 1
                    else:
                        output.write_bytes(expected)
                        print(
                            f"  wrote {output.relative_to(root)} "
                            f"({len(payload)} bytes of {format_name.upper()})"
                        )
                if check and status == 0 and shadercross is not None:
                    print(f"  ok    {name} (SPIR-V + MSL)")
    except (OSError, RuntimeError) as error:
        print(f"FAIL: {error}")
        return 1

    if check:
        if status:
            print("shaders: FAILED")
        elif shadercross is None:
            requested, _ = configured_tool("SHADERCROSS", "shadercross", environment)
            print(
                f"SKIP: SPIR-V is current, but SHADERCROSS={requested} was not found; MSL is unchecked"
            )
            print(
                "      Install an official libsdl-org/SDL_shadercross artifact or set SHADERCROSS."
            )
            return 77
        else:
            print(f"shaders: ok ({len(sources)} GLSL sources, SPIR-V + MSL up to date)")
        if status and shadercross is None:
            print(
                "      MSL is also unchecked because the official SDL_shadercross CLI was not found."
            )
    return status


def main(
    argv: Sequence[str] | None = None,
    *,
    root: Path = ROOT,
    environment: Mapping[str, str] | None = None,
) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments not in ([], ["--check"]):
        print("usage: tools/build/build_shaders.py [--check]", file=sys.stderr)
        return 2
    return process_shaders(
        root,
        os.environ if environment is None else environment,
        arguments == ["--check"],
    )


if __name__ == "__main__":
    raise SystemExit(main())
