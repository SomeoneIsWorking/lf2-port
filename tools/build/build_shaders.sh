#!/bin/sh
# Compile runtime/shaders/*.frag to SPIR-V and commit the result as C arrays.
#
# WHY THE OUTPUT IS COMMITTED. This port builds with a C compiler and SDL and nothing else,
# on purpose, and requiring a shader compiler to build it would make the HD2D pass a thing
# only developers can see -- which is the same failure as putting a feature behind an
# environment variable. SPIR-V is architecture-neutral and reproducible, so the compiled
# blob is as portable as the source it came from, and checking it in costs about 12 KB.
#
# Run this after editing any shader, and commit runtime/shaders/gen/ with it. `ctest shaders`
# recompiles and compares whenever glslc is present, so a stale blob fails the build rather
# than quietly shipping last week's lighting.
#
#   tools/build/build_shaders.sh            regenerate runtime/shaders/gen/
#   tools/build/build_shaders.sh --check    exit 1 if anything committed is out of date
set -eu

# ../.. -- this script lives in tools/build/, so the repo root is two levels up.
cd "$(dirname "$0")/../.."
SRC=runtime/shaders
GEN=$SRC/gen

check=0
[ "${1:-}" = "--check" ] && check=1

GLSLC=${GLSLC:-glslc}
if ! command -v "$GLSLC" >/dev/null 2>&1; then
    echo "SKIP: no $GLSLC. The committed SPIR-V in $GEN is what the build uses; it can be"
    echo "      regenerated on any machine with shaderc (Fedora: dnf install glslc)."
    exit 77
fi

mkdir -p "$GEN"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

status=0
count=0
for f in "$SRC"/*.frag; do
    [ -e "$f" ] || { echo "FAIL: no shaders in $SRC -- nothing was compiled"; exit 1; }
    name=$(basename "$f" .frag)
    out=$GEN/${name}_spv.h

    # -O for size; the optimiser is deterministic, so the same source gives the same bytes
    # on any machine with the same shaderc, which is what makes --check meaningful.
    "$GLSLC" -O -fshader-stage=fragment "$f" -o "$tmp/$name.spv"

    {
        echo "/* GENERATED by tools/build/build_shaders.sh from $f -- do not edit."
        echo " * Regenerate and commit after changing the shader; ctest shaders checks it. */"
        echo "static const unsigned char ${name}_spv[] = {"
        od -An -v -tu1 "$tmp/$name.spv" | tr -s ' ' | sed 's/^ //; s/ /,/g; s/$/,/; s/^/    /'
        echo "};"
    } > "$tmp/$name.h"

    count=$((count + 1))
    if [ "$check" = 1 ]; then
        if [ ! -f "$out" ]; then
            echo "FAIL: $out is missing -- run tools/build/build_shaders.sh"; status=1
        elif ! cmp -s "$tmp/$name.h" "$out"; then
            echo "FAIL: $out is stale -- $f has changed since it was compiled"; status=1
        else
            echo "  ok    $name"
        fi
    else
        cp "$tmp/$name.h" "$out"
        echo "  wrote $out ($(wc -c < "$tmp/$name.spv") bytes of SPIR-V)"
    fi
done

if [ "$count" = 0 ]; then
    echo "FAIL: $SRC held no .frag files, so NOTHING was compiled or checked"
    exit 1
fi
[ "$check" = 1 ] && [ "$status" = 0 ] && echo "shaders: ok ($count up to date)"
[ "$check" = 1 ] && [ "$status" != 0 ] && echo "shaders: FAILED"
exit $status
